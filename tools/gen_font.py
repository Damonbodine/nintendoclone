# Character order in the sheet
CHAR_ORDER = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-x!."

# Build image
glyph_w, glyph_h = 8, 8
img = Image.new('RGBA', (glyph_w * len(CHAR_ORDER), glyph_h), T)

for i, ch in enumerate(CHAR_ORDER):
    if ch not in GLYPHS:
        continue
    rows = GLYPHS[ch]
    for y, row in enumerate(rows):
        for x, pixel in enumerate(row):
            if pixel == '#':
                img.putpixel((i * glyph_w + x, y), W)

out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'fonts', 'nes_font.png')
img.save(out)
print(f"Saved {out} ({img.size[0]}x{img.size[1]}, {len(CHAR_ORDER)} glyphs)")

# Also write the character map so the game code knows the order
map_out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'fonts', 'nes_font_map.txt')
with open(map_out, 'w') as f:
    f.write(CHAR_ORDER)
print(f"Saved {map_out}")
